// ヒーロー用「カット素材」の定義
// 連続動作の補間ではなく、構図の違う4カットをディゾルブで繋ぐ編集にするための素材。
// AI生成の静止画は毎回わずかに絵が変わるため、同一構図で連続再生すると背景や体型が揺れる。
// 構図を変えたカット同士なら、その差は「編集」として自然に見える。
//
// 全カット共通の制約:
//   - 横長16:9（1536×864相当）
//   - 画面左55%は見出し・CTAが重なるため、無地の壁と床だけの余白にする

const RULES = `
【最重要ルール】
・画像内に文字・ロゴ・数字・記号・透かしを一切入れない
・実在企業のロゴ・商標・実在人物の顔を再現しない
・指の本数・関節の向きが破綻しないこと
・器具が浮かない、接地・把持が物理的に正しいこと
`;

const TONE = `
【色・雰囲気ルール】
・ウォームオフホワイト #FBF8F5 とウォームグレージュ #F4EDE8 の空間
・木部はライトオーク、金属パーツはブラスゴールド（クローム/シルバーは使わない）
・自然光主体の柔らかい昼光。中〜低彩度、穏やかなコントラスト。白飛び・黒つぶれを作らない
・避ける色：ネオン、紫〜青のグラデーション、深緑・セージグリーン
・実際のカメラマンが撮影した商業写真の質感。イラスト・3DCG・アニメ調にしない
・添付の参照画像と同じ部屋・同じ照明・同じ世界観に見えること
`;

const FRAMING = `
【構図（全カット共通・厳守）】
横長16:9（1536×864相当）。**画面左55%は什器の少ない無地の壁と床だけの余白**にする（ここにHTMLで見出しとボタンを重ねるため、人物・器具・装飾を一切置かない）。被写体は画面右45%に収める。
`;

