function buildPrompt({ scene, composition, mood, orientation }) {
  const aspect =
    orientation === "pc"
      ? "アスペクト比 16:9 程度の横長構図。横方向に十分な余白を持たせ、主題を画面内でバランスよく配置する。"
      : "アスペクト比 4:5 程度の縦長構図。縦方向に十分な余白（上下）を持たせ、主題を画面中央〜やや上寄りに配置する。";

  return [
    "あなたはトップクラスの採用サイト向けイラストレーターです。",
    "目的：架空の地域密着型スーパーマーケット「株式会社トドマツ」の新卒採用サイト用イラストを1枚生成する。",
    "────────────────",
    "【最重要ルール】",
    "・フラットな線画イラストとして生成する（実写・3DCG・アニメ調の塗りは禁止）",
    "・画像内にテキスト・ロゴ・文字・数字・透かしは一切入れない",
    "・特定の実在企業のロゴ・商標を再現しない（架空の一般的なスーパーマーケットとする）",
    "────────────────",
    `【シーン】\n${scene}`,
    `【構図】\n${composition}\n${aspect}`,
    `【雰囲気】\n${mood}`,
    `【スタイル共通ルール】\n${STYLE_BASE}`,
    "【出力条件】",
    "・そのまま採用サイトのメインビジュアルとして使える品質",
    "・スマートフォン・PCどちらで見ても主題が判別しやすい",
  ].join("\n\n");
}

