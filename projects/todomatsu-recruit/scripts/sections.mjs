function sectionsForOrientation() {
  const list = [];
  for (const moment of moments) {
    for (const orientation of ["pc", "sp"]) {
      list.push({
        id: `${moment.id}-${orientation}`,
        title: `${project.title}｜${moment.label}（${orientation.toUpperCase()}）`,
        imageName: `${moment.id}-${orientation}.png`,
        prompt: buildPrompt({ ...moment, orientation }),
      });
    }
  }
  for (const portrait of portraits) {
    list.push({
      id: portrait.id,
      title: `${project.title}｜${portrait.label}`,
      imageName: `${portrait.id}.png`,
      prompt: buildPrompt({ ...portrait, orientation: "sp" }),
    });
  }
  return list;
}

export const sections = sectionsForOrientation();
